/*
# Copper and Crown — Core Schema

## Overview
Creates the complete database schema for Copper and Crown, an electrical products and services company.
Supports customer accounts, product catalog, service requests, quotes, order tracking, and admin management.
Architecture is designed so a future mobile app can reuse the same backend.

## New Tables
1. `profiles` — Extends auth.users with customer info and role (customer/admin)
2. `products` — Electrical products for sale (sku, name, price, stock, category, images)
3. `services` — Electrical services offered (name, base price, category, description)
4. `orders` — Customer purchase orders with status tracking and shipping info
5. `order_items` — Line items within orders (product snapshot, quantity, price)
6. `service_requests` — Customer requests for electrical services
7. `quotes` — Quotes generated by admin for service requests
8. `service_bookings` — Confirmed service appointments from accepted quotes

## Security
- RLS enabled on ALL tables
- `is_admin()` SECURITY DEFINER function checks raw_app_meta_data for admin role
- Public read on products and services (anon + authenticated)
- Owner-scoped CRUD on orders, service_requests, quotes, service_bookings
- Admin full access on all business tables
- Profiles: users manage own; admins read all
*/

-- ============================================================
-- Helper: is_admin()
-- ============================================================
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT coalesce(
    (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin',
    false
  );
$$;

-- ============================================================
-- profiles
-- ============================================================
CREATE TABLE IF NOT EXISTS public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name text NOT NULL DEFAULT '',
  phone text DEFAULT '',
  company text DEFAULT '',
  role text NOT NULL DEFAULT 'customer' CHECK (role IN ('customer', 'admin')),
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "profiles_select_own_or_admin" ON public.profiles;
CREATE POLICY "profiles_select_own_or_admin" ON public.profiles FOR SELECT
  TO authenticated USING (auth.uid() = id OR public.is_admin());

DROP POLICY IF EXISTS "profiles_insert_own" ON public.profiles;
CREATE POLICY "profiles_insert_own" ON public.profiles FOR INSERT
  TO authenticated WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "profiles_update_own" ON public.profiles;
CREATE POLICY "profiles_update_own" ON public.profiles FOR UPDATE
  TO authenticated USING (auth.uid() = id) WITH CHECK (auth.uid() = id);

